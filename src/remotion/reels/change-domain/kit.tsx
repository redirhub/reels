/** Smoothstep: starts and ends at rest (no first-frame jolt). */
export const smooth = (x: number) => { const k = clamp(x); return k * k * (3 - 2 * k); };
/** Blend two colours (any CSS colour) by k, so a state change fades instead of flipping in one frame. */
export const mix = (a: string, b: string, k: number) => `color-mix(in srgb, ${b} ${(clamp(k) * 100).toFixed(1)}%, ${a})`;
/** A true sub-pixel transform: its own layer plus an invisible 0.02° turn, so slow ease tails never step a pixel. */
export const SMOOTH = (x: number, y: number, s = 1) => `translate3d(${x}px, ${y}px, 0) scale(${s}) rotate(0.02deg)`;
/** Opacity + transform (no rotation: nothing in this film tilts). */
export function fx(o = 1, x = 0, y = 0, s = 1): CSSProperties {
    return { opacity: o, visibility: o <= 0.001 ? 'hidden' : 'visible', transform: SMOOTH(x, y, s), willChange: 'transform, opacity', backfaceVisibility: 'hidden' };
}

