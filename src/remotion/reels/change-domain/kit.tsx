/** Zero-mean dither over a room's gradient, so 8-bit gradients (and the encoder) can't band. Static and seeded. */
function Dither({ strength }: { strength: number }) {
    return (
        <svg aria-hidden="true" style={{ position: 'absolute', inset: 0, width: '100%', height: '100%', opacity: strength, mixBlendMode: 'overlay', pointerEvents: 'none' }}>
            <filter id="w44-dither" x="0" y="0" width="100%" height="100%">
                <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" seed="44" stitchTiles="stitch" />
                <feColorMatrix type="saturate" values="0" />
            </filter>
            <rect width="100%" height="100%" filter="url(#w44-dither)" />
        </svg>
    );
}
const DITHER: Record<Room, number> = { light: 0.06, glow: 0.12, glowTeal: 0.12, sweep: 0.1, radial: 0.1, charcoal: 0.1 };

/** A full-frame room. The light room's dots drift a few px over the scene so a held frame never reads as frozen. */
export function RoomBg({ room, t = 0, opacity = 1 }: { room: Room; t?: number; opacity?: number }) {
    const dx = Math.sin(t / 3.7) * 6, dy = Math.cos(t / 4.3) * 4;
    return (
        <AbsoluteFill style={{ background: ROOM_BG[room], opacity }}>
            {room === 'light' && <div style={{ ...DOTS, transform: SMOOTH(dx, dy), willChange: 'transform' }} />}
            <Dither strength={DITHER[room]} />
        </AbsoluteFill>
    );
}

/** Scene entrance over the lap: the incoming room is laid down first as a cover (no double exposure), then the
    content fades in on top. One eased phase drives both, so the cut never stalls between them. `blend` mixes a
    second room in over the first (a room change inside a scene, e.g. light → glow). */
export function SceneFade({ t, room, inD = 0.32, outAt, outD = 0.3, blend, carry, children }: {
    t: number; room: Room; inD?: number; outAt?: number; outD?: number; blend?: { room: Room; k: number };
    /** Drawn over the cover at full opacity: a shared element carried across the cut. */
    carry?: ReactNode; children: ReactNode;
}) {
    const out = outAt === undefined ? 1 : 1 - easeOut(prog(t, outAt, outAt + outD));
    const ph = easeInOut(prog(t, 0, inD));
    const cover = clamp(ph / 0.6);
    const o = clamp((ph - 0.25) / 0.75) * out;
    return (
        <AbsoluteFill style={{ fontFamily: DISPLAY, color: DARK_ROOM[room] ? C.ink : C.char, WebkitFontSmoothing: 'antialiased' }}>
            <RoomBg room={room} t={t} opacity={cover * out} />
            {blend && blend.k > 0 && <RoomBg room={blend.room} t={t} opacity={smooth(blend.k) * cover * out} />}
            <AbsoluteFill style={{ opacity: o }}>{children}</AbsoluteFill>
            {carry}
        </AbsoluteFill>
    );
}

/* ---------------------------------------------------------------- motion */
/** Pop-in: scale from 0.86 with a little overshoot; opacity on a smoothstep. */
export function popIn(t: number, a: number, d = 0.42, from = 0.86): CSSProperties {
    const k = prog(t, a, a + d);
    return fx(smooth(k * 2.2), 0, 0, from + (1 - from) * easeBack(k));
}
/** Slide in from a side (dx) or below (dy): position eases out, opacity in and out. */
export function slideIn(t: number, a: number, d = 0.45, dx = 0, dy = 30): CSSProperties {
    const q = prog(t, a, a + d), k = easeOut(q);
    return fx(smooth(q * 1.6), (1 - k) * dx, (1 - k) * dy);
}
/** 1 → 0 over [b, b+d] (multiply into opacity). */
export const outK = (t: number, b: number, d = 0.3) => 1 - smooth(prog(t, b, b + d));
/** Eased 0 → 1 over [a, a+d], starting and ending at rest. */
export const ease = (t: number, a: number, d = 0.5) => easeInOut(prog(t, a, a + d));

/** A word or value that changes rolls: the old one rolls up and out as the new one rolls in (never a one-frame swap). */
export function Roll({ from, to, k, h, style }: { from: ReactNode; to: ReactNode; k: number; h: number; style?: CSSProperties }) {
    const e = easeInOut(clamp(k));
    if (e <= 0) return <span style={style}>{from}</span>;
    if (e >= 1) return <span style={style}>{to}</span>;
    return (
        <span style={{ position: 'relative', display: 'inline-block', verticalAlign: 'bottom', height: h, overflow: 'hidden', ...style }}>
            <span style={{ display: 'inline-block', opacity: 1 - e, transform: SMOOTH(0, -e * h * 0.9), willChange: 'transform' }}>{from}</span>
            <span style={{ position: 'absolute', left: 0, top: 0, whiteSpace: 'nowrap', opacity: e, transform: SMOOTH(0, (1 - e) * h * 0.9), willChange: 'transform' }}>{to}</span>
        </span>
    );
}

