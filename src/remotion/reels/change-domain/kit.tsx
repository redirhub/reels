/** A path that draws on as `k` goes 0 → 1 (pathLength-normalised dash). */
export function DrawPath({ d, k, stroke, width = 3, opacity = 1, dash, cap = 'round', style }: { d: string; k: number; stroke: string; width?: number; opacity?: number; dash?: string; cap?: 'round' | 'butt'; style?: CSSProperties }) {
    const e = clamp(k);
    if (dash) {
        // A dashed line can't use the dash trick: it reveals through a mask path that draws instead.
        const id = `m${Math.abs(hash(d))}`;
        return (
            <g style={style}>
                <mask id={id} maskUnits="userSpaceOnUse" x="0" y="0" width="1920" height="1080"><path d={d} fill="none" stroke="#FFFFFF" strokeWidth={width + 8} pathLength={1} strokeDasharray="1 1" strokeDashoffset={1 - e} strokeLinecap="butt" /></mask>
                <path d={d} fill="none" stroke={stroke} strokeWidth={width} strokeOpacity={opacity} strokeDasharray={dash} strokeLinecap={cap} mask={`url(#${id})`} />
            </g>
        );
    }
    return <path d={d} fill="none" stroke={stroke} strokeWidth={width} strokeOpacity={opacity * (e > 0 ? 1 : 0)} strokeLinecap={cap} pathLength={1} strokeDasharray="1 1" strokeDashoffset={1 - e} style={style} />;
}
function hash(s: string) { let h = 0; for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0; return h; }
